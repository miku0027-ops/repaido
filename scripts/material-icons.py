#!/usr/bin/env python3
"""Verify/regenerate pinned Google Material Symbols. Network is used only with --refresh."""
from __future__ import annotations
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / 'web/src/icons'
ASSETS = ICONS / 'material-symbols-rounded'
COMMIT = '49d4db35df873165d6bd6ba09b063c7dafbac2f4'
REPOSITORY = 'https://github.com/google/material-design-icons'
BASE = f'https://raw.githubusercontent.com/google/material-design-icons/{COMMIT}'
NS = '{http://www.w3.org/2000/svg}'
LICENSE_COPIES = (
    ROOT / 'web/public/licenses/material-symbols.txt',
    ROOT / 'engineering/web/public/licenses/material-symbols.txt',
)
FILLED_SYMBOLS = {'favorite', 'bookmark', 'star', 'shopping_cart', 'notifications', 'person'}
STATIC_SYMBOLS = {'directionsCarSvg': 'directions_car', 'twoWheelerSvg': 'two_wheeler', 'storefrontSvg': 'storefront', 'homeSvg': 'home', 'handymanSvg': 'handyman', 'phoneSvg': 'call'}

def asset_keys(mapping: dict[str, str]) -> list[tuple[str, int]]:
    return sorted([(name, 0) for name in set(mapping.values())] + [(name, 1) for name in FILLED_SYMBOLS & set(mapping.values())])

def asset_stem(name: str, fill: int) -> str:
    return name + ('_fill1' if fill else '')

def source_path(name: str, fill: int) -> str:
    return f'symbols/web/{name}/materialsymbolsrounded/{asset_stem(name, fill)}_24px.svg'


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def paths_for(name: str, fill: int = 0) -> tuple[str, list[dict[str, str]]]:
    svg = ET.fromstring((ASSETS / f'{asset_stem(name, fill)}.svg').read_bytes())
    viewbox = svg.attrib.get('viewBox')
    # Two upstream symbols retain legacy 24-unit paths and omit the viewport.
    if viewbox is None and svg.attrib.get('width') == svg.attrib.get('height') == '24':
        viewbox = '0 0 24 24'
    if svg.tag != NS + 'svg' or viewbox not in {'0 -960 960 960', '0 0 24 24'}:
        raise ValueError(f'Unexpected SVG viewport: {name}')
    paths = []
    for child in svg:
        if child.tag != NS + 'path' or set(child.attrib) - {'d', 'fill-rule', 'clip-rule'}:
            raise ValueError(f'Unexpected non-path content: {name}')
        if not child.attrib.get('d'):
            raise ValueError(f'Empty path: {name}')
        paths.append({{'fill-rule': 'fillRule', 'clip-rule': 'clipRule'}.get(k, k): v for k, v in child.attrib.items()})
    if not paths:
        raise ValueError(f'Missing paths: {name}')
    return viewbox, paths


def render(mapping: dict[str, str]) -> dict[Path, str]:
    lines = ['// Generated by scripts/material-icons.py. Source/license: material-symbols.provenance.json.',
             "import { createMaterialIcon } from './createMaterialIcon'",
             "export type { MaterialIconProps, MaterialIcon, LucideIcon, LucideProps } from './createMaterialIcon'", '']
    # Aliases reuse the same component and path declaration. Each factory call is independently tree-shakeable.
    groups: dict[str, list[str]] = {}
    for export, symbol in mapping.items():
        groups.setdefault(symbol, []).append(export)
    for symbol, exports in sorted(groups.items()):
        viewbox, paths = paths_for(symbol)
        primary, *aliases = sorted(exports)
        filled_argument = ''
        if symbol in FILLED_SYMBOLS:
            filled_viewbox, filled_paths = paths_for(symbol, 1)
            if filled_viewbox != viewbox:
                raise ValueError(f'Variant viewport mismatch: {symbol}')
            filled_argument = ', ' + json.dumps(filled_paths, separators=(',', ':'))
        lines.append(f'export const {primary} = /*#__PURE__*/ createMaterialIcon({json.dumps(primary)}, {json.dumps(symbol)}, {json.dumps(paths, separators=(",", ":"))}, {json.dumps(viewbox)}{filled_argument})')
        for alias in aliases:
            lines.append(f'export const {alias} = {primary}')
    static_lines = ['// Generated by scripts/material-icons.py; decorative Leaflet glyphs without React server runtime.']
    for export, symbol in STATIC_SYMBOLS.items():
        viewbox, paths = paths_for(symbol)
        markup = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" width="24" height="24" class="repaido-icon material-symbols-rounded" data-icon="{symbol}" data-icon-size="24" data-icon-fill="0" style="--icon-size:24px;fill:currentColor;stroke:none;stroke-width:0" fill="currentColor" stroke="none" aria-hidden="true" focusable="false">'
        for path in paths:
            markup += f'<path d="{path["d"]}" fill="currentColor" stroke="none"/>'
        markup += '</svg>'
        static_lines.append(f'export const {export} = ' + json.dumps(markup))
    return {ICONS / 'index.ts': '\n'.join(lines) + '\n', ICONS / 'map-icons.ts': '\n'.join(static_lines) + '\n'}


def refresh(mapping: dict[str, str]) -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    def download(key: tuple[str, int]) -> dict[str, object]:
        symbol, fill = key
        relative = source_path(symbol, fill)
        data = urllib.request.urlopen(f'{BASE}/{relative}', timeout=30).read()
        path = ASSETS / f'{asset_stem(symbol, fill)}.svg'
        path.write_bytes(data)
        return {'symbol': symbol, 'axes': {'FILL': fill, 'wght': 400, 'GRAD': 0, 'opsz': 24}, 'path': str(path.relative_to(ICONS)), 'upstream_path': relative, 'sha256': digest(data), 'bytes': len(data)}
    assets = list(ThreadPoolExecutor(max_workers=8).map(download, asset_keys(mapping)))
    license_data = urllib.request.urlopen(f'{BASE}/LICENSE', timeout=30).read()
    (ICONS / 'LICENSE.material-symbols.txt').write_bytes(license_data)
    for destination in LICENSE_COPIES:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(license_data)
    provenance = {'repository': REPOSITORY, 'commit': COMMIT, 'family': 'Material Symbols Rounded', 'axes': {'FILL': 0, 'wght': 400, 'GRAD': 0, 'opsz': 24}, 'license': 'Apache-2.0', 'license_file': 'LICENSE.material-symbols.txt', 'license_sha256': digest(license_data), 'assets': assets}
    (ICONS / 'material-symbols.provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')


def verify(mapping: dict[str, str]) -> None:
    manifest = json.loads((ICONS / 'material-symbols.provenance.json').read_text())
    if manifest['commit'] != COMMIT or manifest['repository'] != REPOSITORY:
        raise ValueError('Provenance does not match pinned upstream')
    if digest((ICONS / manifest['license_file']).read_bytes()) != manifest['license_sha256']:
        raise ValueError('License checksum mismatch')
    for destination in LICENSE_COPIES:
        if not destination.is_file() or digest(destination.read_bytes()) != manifest['license_sha256']:
            raise ValueError(f'Distributed license missing or changed: {destination.relative_to(ROOT)}')
    keys = [(a['symbol'], a['axes']['FILL']) for a in manifest['assets']]
    if sorted(keys) != asset_keys(mapping):
        raise ValueError('Mapped symbols/variants and provenance assets differ')
    for asset in manifest['assets']:
        if asset['upstream_path'] != source_path(asset['symbol'], asset['axes']['FILL']):
            raise ValueError('Unexpected upstream variant source')
        data = (ICONS / asset['path']).read_bytes()
        if digest(data) != asset['sha256'] or len(data) != asset['bytes']:
            raise ValueError(f'Asset checksum mismatch: {asset["symbol"]}')
    for base in [ROOT / 'web/src', ROOT / 'engineering/web/src']:
        for file in base.rglob('*.tsx'):
            for match in re.finditer(r'import\s+(?:type\s+)?\{([^}]+)\}\s+from\s+[\'\"]([^\'\"]*icons)[\'\"]', file.read_text(), re.S):
                if not match[2].endswith('/icons'):
                    continue
                for item in match[1].split(','):
                    name = re.sub(r'^type\s+', '', item.strip()).split(' as ')[0].strip()
                    if name not in mapping and name not in {'MaterialIconProps', 'MaterialIcon', 'LucideIcon', 'LucideProps'}:
                        raise ValueError(f'Missing named export {name} imported by {file.relative_to(ROOT)}')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify sources and generated files without modifying files')
    parser.add_argument('--refresh', action='store_true', help='Download exact pinned upstream source and update provenance')
    args = parser.parse_args()
    if args.check and args.refresh:
        parser.error('--check and --refresh are mutually exclusive')
    mapping = json.loads((ICONS / 'material-symbols.map.json').read_text())
    if args.refresh:
        refresh(mapping)
    verify(mapping)
    generated = render(mapping)
    for file, text in generated.items():
        if args.check:
            if not file.exists() or file.read_text() != text:
                raise ValueError(f'Generated file is stale: {file.relative_to(ROOT)}')
        else:
            file.write_text(text)
    print(f'Material Symbols verified: {len(mapping)} named exports, {len(set(mapping.values()))} unique symbols / {len(asset_keys(mapping))} pinned assets, Apache-2.0, {COMMIT}')


if __name__ == '__main__':
    main()
