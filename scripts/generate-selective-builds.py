"""Generate small release pipelines from the reviewed full-release steps.

Run with --check in local verification; no cloud access or build is involved.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIPELINES = {
    'web': (
        'require-explicit-release', 'check-build-history-access',
        'web-tests-and-build', 'await-release-turn', 'deploy-firebase-hosting',
    ),
    'api': (
        'require-explicit-release', 'check-build-history-access',
        'backend-tests', 'build-api', 'push-api', 'deploy-candidate',
        'await-release-turn', 'deploy-work-services', 'promote-backend',
        'promote-work-services',
    ),
    'rules': (
        'require-explicit-release', 'check-build-history-access',
        'check-firestore-rules-access', 'await-release-turn',
        'deploy-firestore-rules',
    ),
}


def blocks(source):
    start = source.index('steps:\n') + len('steps:\n')
    end = source.index('\nsubstitutions:\n', start)
    body = source[start:end]
    matches = list(re.finditer(r'^  - id: ([\w-]+)\n', body, re.M))
    result = {}
    for index, match in enumerate(matches):
        next_start = matches[index + 1].start() if index + 1 < len(matches) else len(body)
        result[match.group(1)] = body[match.start():next_start].rstrip() + '\n'
    return result, source[end + 1:]


RULES_TEST = '''  - id: firestore-rules-tests
    name: node:24-trixie-slim
    entrypoint: bash
    args:
      - -ceu
      - |
        apt-get update
        apt-get install --yes --no-install-recommends openjdk-21-jre-headless
        npm install --global firebase-tools@15.32.1
        firebase emulators:exec --project=demo-repaido-security --only=firestore --config=firebase.security-tests.json 'node scripts/test-firestore-security.mjs'
'''

VERIFY = '''  - id: verify-selective-release
    name: python:3.12-slim
    entrypoint: python3
    args: ['scripts/verify-release.py', '--target={target}', '--build=$BUILD_ID', '--commit=$COMMIT_SHA']
'''


def render(target, source):
    steps, tail = blocks(source)
    selected = []
    for name in PIPELINES[target]:
        if name not in steps:
            raise ValueError(f'Missing canonical build step: {name}')
        if target == 'rules' and name == 'await-release-turn':
            selected.append(RULES_TEST)
        block = steps[name]
        if target == 'web' and name == 'web-tests-and-build':
            # Rules have their own tested release target; a web-only build does
            # not need Java or a Firestore emulator on every UI edit.
            first = block.index('        apt-get update\n')
            last = block.index('        pnpm install --frozen-lockfile', first)
            block = block[:first] + '        npm install --global pnpm@11.19.0\n' + block[last:]
        selected.append(block)
    if target != 'rules':
        selected.append(VERIFY.format(target=target))
    # API deployment already pushes the image before candidate checks.
    # Avoid a second automatic push after the build succeeds.
    tail = re.sub(r'^images:\n(?:  - .*\n)+', '', tail, flags=re.M)
    return (f'# Generated by scripts/generate-selective-builds.py from cloudbuild.yaml.\n'
            f'# Manual release only; keep _RELEASE_APPROVED false on triggers.\n'
            'steps:\n' + '\n'.join(block.rstrip() for block in selected) + '\n\n' + tail)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT / 'cloudbuild.yaml').read_text()
    for target in PIPELINES:
        path = ROOT / f'cloudbuild-{target}.yaml'
        expected = render(target, source)
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'{path.name} is stale; regenerate it before release.')
        else:
            path.write_text(expected)
        print(f'{path.name}: {"current" if args.check else "generated"}')


if __name__ == '__main__':
    main()
